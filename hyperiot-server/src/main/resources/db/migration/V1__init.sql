-- HyperIoT schema. Written to run unchanged on PostgreSQL and on H2 (PostgreSQL mode).
-- All timestamps are epoch milliseconds (BIGINT) so that time bucketing is plain integer arithmetic.

CREATE TABLE sys_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(32)  NOT NULL,
    created_at    BIGINT       NOT NULL
);

CREATE TABLE product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_key VARCHAR(32)  NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    description VARCHAR(512),
    node_type   VARCHAR(16)  NOT NULL,
    protocol    VARCHAR(16)  NOT NULL,
    thing_model TEXT         NOT NULL,
    created_at  BIGINT       NOT NULL,
    updated_at  BIGINT       NOT NULL
);

CREATE TABLE device (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_key      VARCHAR(32)  NOT NULL,
    device_name      VARCHAR(64)  NOT NULL,
    nickname         VARCHAR(128),
    device_secret    VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    enabled          BOOLEAN      NOT NULL,
    firmware_version VARCHAR(64),
    ip               VARCHAR(64),
    last_online_at   BIGINT,
    last_offline_at  BIGINT,
    last_seen_at     BIGINT,
    tags             TEXT,
    created_at       BIGINT       NOT NULL,
    CONSTRAINT uk_device UNIQUE (product_key, device_name)
);
CREATE INDEX idx_device_status ON device (status);

CREATE TABLE device_shadow (
    device_id  BIGINT PRIMARY KEY,
    reported   TEXT   NOT NULL,
    desired    TEXT   NOT NULL,
    version    BIGINT NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE telemetry (
    device_id  BIGINT           NOT NULL,
    identifier VARCHAR(64)      NOT NULL,
    ts         BIGINT           NOT NULL,
    num_value  DOUBLE PRECISION,
    str_value  VARCHAR(1024)
);
CREATE INDEX idx_telemetry ON telemetry (device_id, identifier, ts);
CREATE INDEX idx_telemetry_ts ON telemetry (ts);

CREATE TABLE device_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id  BIGINT      NOT NULL,
    identifier VARCHAR(64) NOT NULL,
    level      VARCHAR(16) NOT NULL,
    params     TEXT,
    ts         BIGINT      NOT NULL
);
CREATE INDEX idx_event_device ON device_event (device_id, ts);

CREATE TABLE device_log (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT       NOT NULL,
    direction VARCHAR(8)   NOT NULL,
    topic     VARCHAR(256) NOT NULL,
    payload   VARCHAR(4096),
    ts        BIGINT       NOT NULL
);
CREATE INDEX idx_log_device ON device_log (device_id, id);

CREATE TABLE rule (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(128) NOT NULL,
    description    VARCHAR(512),
    product_key    VARCHAR(32)  NOT NULL,
    device_name    VARCHAR(64),
    logic          VARCHAR(8)   NOT NULL,
    conditions     TEXT         NOT NULL,
    actions        TEXT         NOT NULL,
    level          VARCHAR(16)  NOT NULL,
    enabled        BOOLEAN      NOT NULL,
    created_at     BIGINT       NOT NULL
);

CREATE TABLE alarm (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id       BIGINT       NOT NULL,
    rule_name     VARCHAR(128) NOT NULL,
    device_id     BIGINT       NOT NULL,
    product_key   VARCHAR(32)  NOT NULL,
    device_name   VARCHAR(64)  NOT NULL,
    level         VARCHAR(16)  NOT NULL,
    status        VARCHAR(16)  NOT NULL,
    message       VARCHAR(512),
    trigger_value VARCHAR(256),
    triggered_at  BIGINT       NOT NULL,
    recovered_at  BIGINT,
    acked_at      BIGINT
);
CREATE INDEX idx_alarm_status ON alarm (status, triggered_at);
CREATE INDEX idx_alarm_rule_device ON alarm (rule_id, device_id, status);

CREATE TABLE command (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  VARCHAR(40)  NOT NULL UNIQUE,
    device_id   BIGINT       NOT NULL,
    product_key VARCHAR(32)  NOT NULL,
    device_name VARCHAR(64)  NOT NULL,
    identifier  VARCHAR(64)  NOT NULL,
    params      TEXT,
    status      VARCHAR(16)  NOT NULL,
    response    TEXT,
    created_at  BIGINT       NOT NULL,
    sent_at     BIGINT,
    replied_at  BIGINT,
    expire_at   BIGINT       NOT NULL
);
CREATE INDEX idx_command_device ON command (device_id, status);
CREATE INDEX idx_command_status ON command (status, created_at);

CREATE TABLE firmware (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_key VARCHAR(32)  NOT NULL,
    version     VARCHAR(64)  NOT NULL,
    name        VARCHAR(128),
    description VARCHAR(512),
    file_name   VARCHAR(128) NOT NULL,
    size        BIGINT       NOT NULL,
    sha256      VARCHAR(64)  NOT NULL,
    created_at  BIGINT       NOT NULL,
    CONSTRAINT uk_firmware UNIQUE (product_key, version)
);

CREATE TABLE ota_task (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    firmware_id BIGINT       NOT NULL,
    product_key VARCHAR(32)  NOT NULL,
    status      VARCHAR(16)  NOT NULL,
    created_at  BIGINT       NOT NULL
);

CREATE TABLE ota_task_device (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    BIGINT      NOT NULL,
    device_id  BIGINT      NOT NULL,
    status     VARCHAR(16) NOT NULL,
    progress   INT         NOT NULL,
    message    VARCHAR(256),
    updated_at BIGINT      NOT NULL
);
CREATE INDEX idx_otad_task ON ota_task_device (task_id);
CREATE INDEX idx_otad_device ON ota_task_device (device_id, status);
